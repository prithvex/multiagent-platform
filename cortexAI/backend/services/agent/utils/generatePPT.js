import PptxGenJS from 'pptxgenjs'

const COLORS = {
    primary: "2563EB",
    secondary: "BF172A",
    text: "334155",
    light: "F8FAFC",
    border: "E2E8F0",
    white: "FFFFFF",
    muted: "647488",
};

const generateppt = async (data) => {

    // creating the coverpage functions 
    const addCover = (ppt, data) => {
        const slide = ppt.addslide();
        slide.background = {
            color: COLORS.primary
        }

        slide.addShape(ppt.ShapeType.rect, {
            x: 0,
            y: 0,
            w: "100%",
            h: "100%",
            fill: {
                color: "FFFFFF",
                alpha: 10
            },
            line: {
                color: "000000",
                alpha: 0
            }
        })

        slide.addText(data.title, {
            x: "25%",
            y: "25%",
            w: "50%",
            h: "50%",
            color: "FFFFFF",
            fontSize: 28,
            bold: true,
            align: "center"
        })

        slide.addText(data.subtitle, {
            x: "25%",
            y: "45%",
            w: "50%",
            h: "50%",
            color: "FFFFFF",
            fontSize: 14,
            align: "center"
        })

        slide.addText("Generated by cortexAI", {
            x: "25%",
            y: "80%",
            w: "50%",
            h: "50%",
            color: "FFFFFF",
            fontSize: 14,
            align: "center"
        })
    }

    const addContentSlide = (ppt, title, points, page, totalSlides) => {
        const slide = ppt.addslide();
        //apply theme
        slide.background = {
            color: COLORS.white
        }
        slide.addText(title, {
            x: "10%",
            y: "10%",
            w: "80%",
            h: "10%",
            color: COLORS.primary,
            fontSize: 24,
            bold: true,
            align: "left"
        })

        slide.addShape(ppt.ShapeType.line, {
            x: "10%",
            y: "22%",
            w: "80%",
            h: "0",
            line: {
                color: COLORS.muted,
                width: 1.5
            }
        })

        const visiblePoints = points.slice(0, 6);
        visiblePoints.forEach((point, index) => {
            const y = 1.2 + (index * 0.75);

            slide.addShape(ppt.ShapeType.roundRect, {
                x: 1.2,
                y: y,
                w: "15",
                h: "0.45",
                fill: {
                    color: i % 2 ? "FFFFFF" : "F1F5F9",
                },
                line: {
                    color: "000000",
                    alpha: 0
                },
                textFrame: {
                    text: "\u2022"
                }
            })

            slide.addShape(ppt.ShapeType.ellipse, {
                x: 1.2,
                y: y,
                w: "15",
                h: "0.45",
                fill: {
                    color: "FFFFFF",
                },
                line: {
                    color: "000000",
                    alpha: 0
                },
                textFrame: {
                    text: "\u2022"
                }
            })

            slide.addText(point, {
                x: "10%",
                y: "24%",
                w: "80%",
                h: "10%",
                color: "334155",
                fontSize: 18,
                bold: true,
                align: "left",
                valign: "middle"
            })

            slide.addText(`${page}/${totalSlides}`, {
                x: "90%",
                y: "5%",
                w: "10%",
                h: "10%",
                color: "647488",
                fontSize: 12,
                bold: false,
                align: "right",
                valign: "middle"
            })

            slide.addText(`CortexAI`, {
                x: "10%",
                y: "90%",
                w: "10%",
                h: "10%",
                color: COLORS.muted,
                fontSize: 12,
                bold: false,
                align: "left",
                valign: "middle"
            })

        })
        const addThankyouPage = (ppt) => {
            const slide = ppt.addSlide();
            slide.background = {
                color: COLORS.primary

            }
            slide.addText(data.title, {
                x: "10%",
                y: "10%",
                w: "80%",
                h: "10%",
                color: "FFFFFF",
                fontSize: 28,
                bold: true,
                align: "left"
            })

            slide.addText(data.subtitle, {
                x: "10%",
                y: "20%",
                w: "80%",
                h: "10%",
                color: "FFFFFF",
                fontSize: 18,
                bold: true,
                align: "left"
            })

            slide.addText(`CortexAI`, {
                x: "10%",
                y: "50%",
                w: "80%",
                h: "10%",
                color: "FFFFFF",
                fontSize: 28,
                bold: true,
                align: "center"
            })

            slide.addText(`Thank you!`, {
                x: "10%",
                y: "60%",
                w: "80%",
                h: "10%",
                color: "FFFFFF",
                fontSize: 28,
                bold: true,
                align: "center"
            })

            slide.addText(`Generated by cortexAI`, {
                x: "10%",
                y: "80%",
                w: "80%",
                h: "10%",
                color: "FFFFFF",
                fontSize: 18,
                bold: true,
                align: "center"
            })
        }


        try {
            const ppt = new PptxGenJS();
            //ppt layout
            ppt.layout = "LAYOUT_WIDESCREEN"
            ppt.author = "CortexAI"
            ppt.subject = data.title
            ppt.title = data.title
            ppt.company = "CortexAI"
            ppt.lang = "en-US"
            ppt.theme = {
                headFontFace: "Aptos",
                bodyFontFace: "Aptos",
                colorScheme: "default"
            }

            // creating coverpage
            addCover(ppt, data)
            data?.slides?.forEach((slide, index) => {
                addContentSlide(ppt, slide.slide_title, slide.key_points, index + 1, data.slides.length)
            });

            //thankyou page
            addThankyouPage(ppt);
            return ppt
        } catch (error) {
            console.log(error)
        }


    }
}