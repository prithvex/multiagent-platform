import PDFDocument from "pdfkit"

export const generatepdf = async (data) => {
    return new Promise((resolve, reject) => {
        try {
            const doc = new PDFDocument({
                size: "A4",
                margin: 50,
                info: {
                    Author: "CortexAI",
                    Title: data.title,
                    Creator: "CortexAI"
                }
            })

            const chunks = []

            doc.on("data", (chunk) => chunks.push(chunk));

            doc.on("end", () => resolve(Buffer.concat(chunks)))

            doc.on("error", (err) => reject(err))

            // data include 

            //title
            doc
                .fontSize(28)
                .text(data.title, {
                    align: "center",
                })
                .fillColor('#111827')

            if (data.subtitle) {
                doc.moveDown(0.5)
            }

            //subtitle   
            doc
                .fontSize(16)
                .text(data.subtitle, {
                    align: "center",
                })
                .fillColor('gray')

            // sections 
            data.moveDown(2)

            data?.sections?.forEach((s) => {
                doc
                    .fontSize(18)
                    .fillColor("#111827")
                    .text(s.heading, {
                        align: "center",
                    });

                doc.moveDown(0.5);

                s?.points?.forEach((point) => {
                    doc
                        .fontSize(18)
                        .fillColor("#111827")
                        .text("•" + point, {
                            align: "left",
                            lineGap: "5"
                        });
                });
                // footer 
                doc.moveDown(1);
                doc
                    .fontSize(10)
                    .fillColor("#021949ff")
                    .text("Generated by cortexAI", {
                        align: "center",
                    });
            })

            doc.end();

        } catch (error) {
            reject(error)
        }
    })
}